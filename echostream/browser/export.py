"""Write the browser bundle from the current serving bundle (artifacts/serving/current).

Only the serving bundle is read: the browser runs the same model version the cluster serves.
"""
from __future__ import annotations

import gzip
import json
from pathlib import Path

import numpy as np
import pandas as pd

from echostream.browser.bundle_format import (CATEGORY_EN, FORMAT, FORMAT_VERSION, BinWriter, QuantConfig,
                                              cf_to_rows, constants_block, dump_json, ranker_to_json,
                                              sha256_file, varint_encode)
from echostream.serving.bundle import ServingBundle, load_bundle

# Demo users: for each of these first-level categories, the real KuaiRec user (>= 40 positives)
# whose last 50 positives contain the largest share of it. Most users are dominated by
# "Everyday news" (the largest category), so the list asks for six visibly different tastes.
DEMO_CATEGORIES = ["舞蹈", "宠物", "亲子", "二次元", "美食", "喜剧"]
MIN_POSITIVES = 40
PROFILE_WINDOW = 50      # = HIST_LEN: the user tower sees the last 50 positives
MODEL_FILE = "model.bin.gz"
PRESETS = {
    "f32": QuantConfig(),
    "f16": QuantConfig(item_emb="f16", id_emb="f16", caption="f16", cf_sims="f16"),
    "int8": QuantConfig(item_emb="i8row", id_emb="i8row", caption="i8row", cf_sims="u8code"),
}
LICENSE_TEXT = """# Data license

This directory is generated by `scripts/export_browser_model.py` from the echostream serving bundle.

It contains data derived from **KuaiRec** (Gao et al., *KuaiRec: A Fully-observed Dataset and Insights
for Evaluating Recommender Systems*, CIKM 2022, https://kuairec.com/, arXiv 2202.10842): video captions
(titles, unchanged Chinese text), category labels, per-video statistics, the interaction histories of a
few anonymous KuaiRec users (by their dataset id), and models trained on the dataset.

KuaiRec is © its authors and licensed under **CC BY-SA 4.0**
(https://creativecommons.org/licenses/by-sa/4.0/). This derived data is shared under the same license,
CC BY-SA 4.0. Changes: captions truncated to 80 characters; numbers quantized as described in
manifest.json; English category names hand-written by the echostream author;
titles_en.json (added by scripts/translate_titles.py, not by the exporter) holds English machine
translations of the captions, made with Qwen (qwen3.8-flash), shared under the same license.
"""


def category_table(b: ServingBundle) -> tuple[list[dict], np.ndarray]:
    en = {k: v for k, v in json.loads(CATEGORY_EN.read_text()).items() if not k.startswith("_")}
    counts = pd.Series(b.category_names).value_counts()
    names = list(counts.index)
    missing = [n for n in names if n not in en]
    if missing:
        raise ValueError(f"no English name for categories {missing}; add them to {CATEGORY_EN.name}")
    index = {n: k for k, n in enumerate(names)}
    return [{"zh": n, "en": en[n], "n_videos": int(counts[n])} for n in names], \
        np.array([index[n] for n in b.category_names], np.int32)


def top_categories(b: ServingBundle, cat_of: np.ndarray, cats: list[dict], u: int, k: int = 3) -> list[dict]:
    h = b.pos_history(u)[-PROFILE_WINDOW:]
    s = pd.Series(cat_of[h]).value_counts(normalize=True).head(k)
    return [{"category": int(c), "en": cats[c]["en"], "share": round(float(v), 3)} for c, v in s.items()]


def pick_demo_users(b: ServingBundle, cat_of: np.ndarray, cats: list[dict]) -> list[int]:
    zh_index = {c["zh"]: k for k, c in enumerate(cats)}
    best: dict[int, tuple[float, int]] = {}
    for u in range(b.n_users):
        h = b.pos_history(u)
        if len(h) < MIN_POSITIVES:
            continue
        share = np.bincount(cat_of[h[-PROFILE_WINDOW:]], minlength=len(cats)) / min(len(h), PROFILE_WINDOW)
        for zh in DEMO_CATEGORIES:
            c = zh_index[zh]
            if share[c] > best.get(c, (-1.0, -1))[0]:
                best[c] = (float(share[c]), u)
    out = []
    for zh in DEMO_CATEGORIES:
        u = best[zh_index[zh]][1]
        if u not in out:
            out.append(u)
    return out


def user_record(b: ServingBundle, u: int) -> dict:
    """Everything the read path knows about user u at the bundle's cutoff."""
    ra, eng = b.rank_assets, b.engine
    recent = b.recent(u)
    return {"uid": int(u), "user_cats": eng.a.user_cats[u].astype(int).tolist(),
            "user_stats": [float(x) for x in ra.user_stats[u]], "cat_aff": [float(x) for x in ra.user_cat_aff[u]],
            "log_dur": float(ra.user_log_dur[u]), "pos": b.pos_history(u).astype(int).tolist(),
            "seen": b.seen(u).astype(int).tolist(), "recent_items": [i for i, _ in recent],
            "recent_wr": [float(np.float32(w)) for _, w in recent]}


def new_user_record(b: ServingBundle, uid: int) -> dict:
    """A brand-new sign-up: every categorical field 'missing' (code 0), no history. The numeric
    features are what build_rank_assets computes for a user with no events (all zero; duration
    preference = the catalog median)."""
    n_fields = b.engine.a.user_cats.shape[1]
    return {"uid": int(uid), "user_cats": [0] * n_fields, "user_stats": [0.0] * b.rank_assets.user_stats.shape[1],
            "cat_aff": [0.0] * b.rank_assets.user_cat_aff.shape[1],
            "log_dur": float(np.float32(np.median(b.rank_assets.item_log_dur))),
            "pos": [], "seen": [], "recent_items": [], "recent_wr": []}


def write_browser_bundle(out: Path, serving_dir: Path, quant: QuantConfig = QuantConfig(),
                         demo_users: list[int] | None = None) -> dict:
    serving_dir = serving_dir.resolve()
    b = load_bundle(serving_dir)
    out.mkdir(parents=True, exist_ok=True)
    a, ra = b.engine.a, b.rank_assets
    n_items = len(a.item_vecs)
    cats, cat_of = category_table(b)
    n_tags = ra.item_cats.shape[1]

    w = BinWriter()
    w.add("item_emb", a.item_vecs, quant.item_emb)
    w.add("id_emb", a.user_tower["item_id_emb"], quant.id_emb)
    w.add("caption", a.caption_emb, quant.caption)
    n_fields = sum(1 for k in a.user_tower if k.startswith("field_"))
    for f in range(n_fields):
        w.add(f"user_field_{f}", a.user_tower[f"field_{f}"], "f32")
    for k in ("w1", "b1", "w2", "b2"):
        w.add(k, a.user_tower[k], "f32")
    counts, ids, sims = cf_to_rows(a.cf_neighbors, a.cf_sims, quant.cf_topk)
    gaps = np.concatenate([np.diff(ids[o:o + c], prepend=0) for o, c in
                           zip(np.concatenate([[0], np.cumsum(counts)[:-1]]), counts)])
    w.add("cf_counts", counts, "u8")
    w.add_raw("cf_id_gaps", varint_encode(gaps), "varint", len(gaps))
    w.add("cf_sims", sims, quant.cf_sims)
    w.add("pop_recent", a.pop_scores["pop_recent"], "f32")
    w.add("pop_platform", a.pop_scores["pop_platform"], "f32")
    w.add("cold", (a.item_hist_count == 0).astype(np.uint8), "u8")
    w.add("item_stats", ra.item_stats, "f32")
    w.add("item_log_dur", ra.item_log_dur, "f32")
    bits = (ra.item_cats.astype(np.uint32) << np.arange(n_tags, dtype=np.uint32)).sum(1).astype(np.uint32)
    w.add("item_cat_bits", bits, "u32")
    # gzip it ourselves: binary files are usually served uncompressed by static hosts
    (out / MODEL_FILE).write_bytes(gzip.compress(bytes(w.buf), 9, mtime=0))

    dump_json(ranker_to_json((serving_dir / "ranker.txt").read_text()), out / "ranker.json")
    dump_json({"titles": b.titles, "category": cat_of.tolist(), "categories": cats,
               "category_names_note": "English category names are hand-written (not machine-translated); "
                                      "titles are the original Chinese captions from KuaiRec."},
              out / "catalog.json")

    demo_users = demo_users or pick_demo_users(b, cat_of, cats)
    users = []
    for u in demo_users:
        rec = user_record(b, u)
        top = top_categories(b, cat_of, cats, u)
        rec.update(kind="real", label=" · ".join(t["en"] for t in top[:2]), top_categories=top,
                   n_positives=len(rec["pos"]), n_seen=len(rec["seen"]))
        users.append(rec)
    new = new_user_record(b, b.n_users)
    new.update(kind="new", label="Brand-new user", top_categories=[], n_positives=0, n_seen=0)
    users.append(new)
    dump_json({"note": "Real KuaiRec users, identified only by their anonymous dataset id. 'uid' "
                       f"{b.n_users} is a synthetic brand-new user (no history, all profile fields missing).",
               "users": users}, out / "users.json")
    (out / "LICENSE.md").write_text(LICENSE_TEXT)

    sources = ["manifest.json", "item_emb.npy", "user_tower.npz", "user_cats.npy", "cf_neighbors.npy",
               "cf_sims.npy", "pop_recent.npy", "pop_platform.npy", "caption_emb.npy", "item_hist_count.npy",
               "rank_assets.npz", "ranker.txt", "history.npz", "item_meta.parquet"]
    manifest = {
        "format": FORMAT, "format_version": FORMAT_VERSION,
        "source": {"version": b.version, "serving_manifest": b.manifest,
                   "sha256": {f: sha256_file(serving_dir / f) for f in sources}},
        "quant": {"name": quant.name, **quant.__dict__},
        "license": "Derived from KuaiRec (CC BY-SA 4.0); see LICENSE.md",
        "n_items": n_items, "n_users": b.n_users,
        "constants": constants_block(dict(a.quotas), a.total, [len(a.user_tower[f"field_{f}"]) for f in range(n_fields)],
                                     n_tags),
        "model_file": MODEL_FILE, "model_bytes": len(w.buf), "arrays": w.table,
        "files": {f: {"bytes": (out / f).stat().st_size, "sha256": sha256_file(out / f)}
                  for f in (MODEL_FILE, "ranker.json", "catalog.json", "users.json")},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1))
    return manifest
